function toFlag(code) {
    return String.fromCodePoint(...[...code].map((c) => 127397 + c.charCodeAt(0)));
}

function country(code, name, cities) {
    return {
        code,
        name,
        flag: toFlag(code),
        cities: cities.map(([cityName, lat, lon]) => ({ name: cityName, lat, lon }))
    };
}

